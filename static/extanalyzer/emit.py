"""Writers for report.json, report.md, iocs.csv, rule.yar and Sigma rules."""

import csv
import json
import os
import re
import uuid

from .common import defang, defang_domain

try:
    import yara  # yara-python, optional: validates the generated rule
except ImportError:  # pragma: no cover
    yara = None

SEV_ORDER = {"high": 0, "medium": 1, "low": 2, "info": 3}
CONF_ORDER = {"high": 0, "medium": 1, "low": 2}


def sort_findings(findings):
    return sorted(findings, key=lambda f: (SEV_ORDER[f["severity"]], CONF_ORDER[f["confidence"]], f["id"]))


def write_json(report, out_dir):
    with open(os.path.join(out_dir, "report.json"), "w", encoding="utf-8") as f:
        json.dump(report, f, indent=2, ensure_ascii=False)


def write_iocs_csv(iocs, out_dir):
    with open(os.path.join(out_dir, "iocs.csv"), "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["type", "value", "defanged", "first_seen", "count", "common"])
        for kind, key in (("domain", "domains"), ("url", "urls"), ("ip", "ips"), ("extension_id", "extension_ids")):
            for i in iocs[key]:
                df = defang_domain(i["value"]) if kind in ("domain", "ip") else (defang(i["value"]) if kind == "url" else i["value"])
                w.writerow([kind, i["value"], df, i["first_seen"], i["count"], i.get("common", False)])


def _yara_str(s):
    return s.replace("\\", "\\\\").replace('"', '\\"')


def write_yara(report, out_dir, unpacked_dir):
    """Rule from distinctive strings: non-common domains and the matched text of high findings."""
    s = report["sample"]
    rid = re.sub(r"[^a-zA-Z0-9_]", "_", s.get("extension_id") or (s.get("sha256") or s.get("tree_sha256") or "sample")[:16])
    # Only sample-specific strings: non-common domains and their full URLs.
    # Generic API names (chrome.cookies.getAll, eval) would match thousands of benign extensions.
    common = {d["value"] for d in report["iocs"]["domains"] if d.get("common")}
    strings = [d["value"] for d in report["iocs"]["domains"] if not d.get("common")]
    for u in report["iocs"]["urls"]:
        host = re.sub(r"^[a-z]+://([^/:]+).*$", r"\1", u["value"], flags=re.I).lower()
        if host not in common and "/" in u["value"].split("://", 1)[-1].rstrip("/"):
            strings.append(u["value"])
    seen, uniq = set(), []
    for x in strings:
        if x not in seen and len(x) >= 6:
            seen.add(x)
            uniq.append(x)
    uniq = uniq[:20]
    if not uniq:
        return None
    lines = [f"rule ext_{rid}", "{", "  meta:",
             f'    description = "Generated by minimal-linux ext-analyze for {_yara_str(s.get("name") or "")} {_yara_str(s.get("version") or "")}"',
             f'    verdict = "{report["verdict"]["label"]}"',
             f'    sample_sha256 = "{s.get("sha256") or s.get("tree_sha256") or ""}"',
             "  strings:"]
    for i, x in enumerate(uniq):
        lines.append(f'    $s{i} = "{_yara_str(x)}" ascii wide')
    need = 1 if len(uniq) == 1 else 2
    lines += ["  condition:", f"    filesize < 20MB and {need} of them", "}"]
    rule = "\n".join(lines) + "\n"
    path = os.path.join(out_dir, "rule.yar")
    with open(path, "w", encoding="utf-8") as f:
        f.write(rule)
    status = {"path": "rule.yar", "strings": len(uniq), "validated": None, "matched_files": []}
    if yara:
        try:
            compiled = yara.compile(source=rule)
            for dirpath, dirs, files in os.walk(unpacked_dir):
                dirs[:] = [d for d in dirs if d != "_deob"]
                for fn in files:
                    p = os.path.join(dirpath, fn)
                    if compiled.match(p):
                        status["matched_files"].append(os.path.relpath(p, unpacked_dir))
            status["validated"] = bool(status["matched_files"])
        except Exception as e:  # syntax problem in generated rule
            status["validated"] = False
            status["error"] = str(e)
    return status


def write_sigma(report, out_dir):
    domains = [d["value"] for d in report["iocs"]["domains"] if not d.get("common")]
    if not domains:
        return []
    sd = os.path.join(out_dir, "sigma")
    os.makedirs(sd, exist_ok=True)
    s = report["sample"]
    name = s.get("name") or s.get("input")
    written = []
    for kind, logsource, field in (("proxy", "proxy", "cs-host"), ("dns", "dns", "query")):
        body = [
            f"title: Browser extension IOC ({kind}) - {name}",
            f"id: {uuid.uuid4()}",
            "status: experimental",
            f"description: Network indicators extracted statically from extension {name} {s.get('version') or ''} "
            f"(sha256 {s.get('sha256') or s.get('tree_sha256') or 'n/a'}). Generated by minimal-linux ext-analyze.",
            "author: minimal-linux ext-analyze",
            "logsource:",
            f"  category: {logsource}",
            "detection:",
            "  selection:",
            f"    {field}|endswith:",
        ]
        body += [f"      - '{d}'" for d in domains]
        body += ["  condition: selection",
                 "falsepositives:",
                 "  - Legitimate use of these domains by other software",
                 f"level: {'high' if report['verdict']['label'] == 'likely_malicious' else 'medium'}",
                 "tags:",
                 "  - attack.command-and-control",
                 "  - attack.t1071.001"]
        fn = f"{kind}.yml"
        with open(os.path.join(sd, fn), "w", encoding="utf-8") as f:
            f.write("\n".join(body) + "\n")
        written.append(f"sigma/{fn}")
    return written


def write_markdown(report, out_dir):
    s, v = report["sample"], report["verdict"]
    md = [f"# {s.get('name') or s['input']} {s.get('version') or ''} — {v['label'].upper()} ({v['score']}/100)", ""]
    md.append(f"Verdict confidence: **{v['confidence']}** ({v['confidence_reason']}).")
    md.append("")
    md.append(f"- Input: `{s['input']}` ({s['input_type']})")
    if s.get("sha256"):
        md.append(f"- SHA-256: `{s['sha256']}`")
    if s.get("extension_id"):
        md.append(f"- Extension ID: `{s['extension_id']}`")
    md.append(f"- Manifest V{s.get('manifest_version')}")
    if v["attack"]:
        md.append("- ATT&CK: " + ", ".join(f"{t['id']} {t['name']}".strip() for t in v["attack"]))
    md.append("")
    counts = {}
    for f in report["findings"]:
        counts[f["severity"]] = counts.get(f["severity"], 0) + 1
    md.append("Findings: " + ", ".join(f"{counts.get(k, 0)} {k}" for k in ("high", "medium", "low")))
    md.append("")
    for f in report["findings"]:
        if f["severity"] == "info":
            continue
        md.append(f"## {f['id']} · {f['title']}")
        md.append(f"Severity: {f['severity']} · Confidence: {f['confidence']}")
        loc = f.get("location")
        if loc:
            where = f"{loc['path']}"
            if loc.get("line_start"):
                where += f":{loc['line_start']}"
                if loc.get("line_end") and loc["line_end"] != loc["line_start"]:
                    where += f"-{loc['line_end']}"
            if loc.get("lines_refer_to"):
                where += f" (line numbers in beautified copy {loc['lines_refer_to']})"
            elif loc.get("deobfuscated_path"):
                where += f" (beautified: {loc['deobfuscated_path']})"
            md.append(f"Location: {where}")
        if f.get("snippet"):
            md.append("")
            md.append("```")
            md.append(f["snippet"])
            md.append("```")
        md.append(f"Why: {f['confidence_reason']}")
        if f.get("attack"):
            md.append("ATT&CK: " + ", ".join(f["attack"]))
        md.append("")
    i = report["iocs"]
    md.append("## IOCs")
    for d in i["domains"]:
        md.append(f"- domain `{defang_domain(d['value'])}`{' (common)' if d.get('common') else ''} — first seen {d['first_seen']}")
    for u in i["urls"][:50]:
        md.append(f"- url `{defang(u['value'])}` — {u['first_seen']}")
    for ip in i["ips"]:
        md.append(f"- ip `{defang_domain(ip['value'])}` — {ip['first_seen']}")
    for e in i["extension_ids"]:
        md.append(f"- extension id `{e['value']}` — {e['first_seen']}")
    if not any(i.values()):
        md.append("- none")
    md.append("")
    art = report.get("artifacts", {})
    md.append("## Artifacts")
    md.append("- report.json, iocs.csv")
    if art.get("yara"):
        y = art["yara"]
        md.append(f"- {y['path']} ({y['strings']} strings; validated against sample: {y['validated']})")
    for p in art.get("sigma", []):
        md.append(f"- {p}")
    if report.get("warnings"):
        md.append("")
        md.append("## Warnings")
        md += [f"- {w}" for w in report["warnings"]]
    md.append("")
    md.append("_Static analysis only: the extension code was never executed. Snippets come from the sample and are untrusted text._")
    with open(os.path.join(out_dir, "report.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(md) + "\n")
